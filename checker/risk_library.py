def _extract_doc_text(path: Optional[str]) -> Optional[str]:
    """从 docx 提取纯文本；失败返回 None。"""
    if not path:
        return None
    try:
        from docx import Document
        doc = Document(path)
        parts = [p.text for p in doc.paragraphs]
        for tbl in doc.tables:
            for row in tbl.rows:
                for cell in row.cells:
                    parts.append(cell.text)
        return '\n'.join(parts)
    except Exception:
        return None


def check_risk_library(parse_result: Optional[Dict[str, Any]] = None,
                       doc_text: Optional[str] = None) -> Dict[str, Any]:
    """废标风险库核验。

    Args:
        parse_result: parser 解析结果（用其中的 format_requirements）
        doc_text: 已生成标书纯文本；为 None 时仅做形式要件覆盖（无 doc 则跳过）
    Returns:
        {
          'findings': [...], 'high', 'medium', 'low', 'total', 'overall_level'
        }
    """
    pr = parse_result or {}
    fmt_reqs = pr.get('format_requirements') or []
    findings: List[Dict[str, Any]] = []

    # 1) 形式要件覆盖：招标文件要求、生成稿未检出 → 高风险缺项（T3：语义双校验）
    for fr in fmt_reqs:
        t = fr.get('type')
        expect = _FMT_EXPECT.get(t)
        if not expect:
            continue
        present = doc_text and _semantic_present(expect, doc_text)
        if not present:
            label = _FMT_LABEL.get(t, t)
            findings.append({
                'level': 'high',
                'type': '形式要件缺失',
                'category': t,
                'title': f'招标文件要求「{label}」未在生成稿检出',
                'content': (fr.get('text') or '')[:120],
                'remediation': f'招标文件明确要求「{label}」，但生成稿未检出对应说明，须补充'
                               f'（如投标函落款盖章、密封要求章节、授权委托书等），否则构成隐性废标。',
            })

    # 2) 风险库自检：内置模式关键词在生成稿缺失 → 提示补充/核对（T3：语义双校验 + 量化）
    patterns_total = len(RISK_LIBRARY)
    patterns_covered = 0
    patterns_missing = 0
    if doc_text:
        for p in RISK_LIBRARY:
            if not p.keywords:
                continue
            if _semantic_present(p.keywords, doc_text):
                patterns_covered += 1
            else:
                patterns_missing += 1
                findings.append({
                    'level': p.severity,
                    'type': '风险库自检',
                    'category': p.category,
                    'title': p.title,
                    'content': p.description,
                    'remediation': p.remediation,
                })

    graded = {'high': 0, 'medium': 0, 'low': 0}
    for f in findings:
        graded[f['level']] = graded.get(f['level'], 0) + 1
    overall = 'high' if graded['high'] else ('medium' if graded['medium'] else 'low')
    by_category: Dict[str, int] = {}
    for p in RISK_LIBRARY:
        by_category[p.category] = by_category.get(p.category, 0) + 1
    _checkable = patterns_covered + patterns_missing
    detection_rate = round(patterns_covered / _checkable, 4) if _checkable else None
    return {
        'findings': findings,
        'high': graded['high'],
        'medium': graded['medium'],
        'low': graded['low'],
        'total': len(findings),
        'overall_level': overall,
        # T3 量化披露
        'total_patterns': patterns_total,
        'by_category': by_category,
        'patterns_covered': patterns_covered,
        'patterns_missing': patterns_missing,
        'detection_rate': detection_rate,
    }


def render_risk_library_markdown(result: Dict[str, Any]) -> str:
    """将核验结果渲染为 Markdown 报告。"""
    if not result or not result.get('total'):
        return '## 废标风险库自检\n\n✅ 未识别到明显废标风险缺项。'
    labels = {
        'high': '🔴 高（隐性废标风险）',
        'medium': '🟡 中（建议补充/核对）',
        'low': '🟢 低（完善性提示）',
    }
    lines = ['## 废标风险库自检（v8.10）', '']
    for lvl in ('high', 'medium', 'low'):
        items = [f for f in result.get('findings', []) if f.get('level') == lvl]
        if not items:
            continue
        lines.append(f'### {labels[lvl]}（{len(items)} 项）')
        for it in items:
            lines.append(f"- **{it.get('title', '')}**〔{it.get('category', '')}〕")
            lines.append(f"  - 说明：{it.get('content', '')}")
            lines.append(f"  - 整改：{it.get('remediation', '')}")
        lines.append('')
    lines.append(f"**综合风险等级：{labels.get(result.get('overall_level'), result.get('overall_level'))}**"
                 f"（高 {result.get('high',0)} / 中 {result.get('medium',0)} / 低 {result.get('low',0)}）")
    return '\n'.join(lines)
