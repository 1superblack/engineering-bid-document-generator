def _semantic_present(keywords, doc_text: Optional[str]) -> bool:
    """字面 OR 语义同义命中（T3 双校验层）。"""
    if not doc_text or not keywords:
        return False
    for k in keywords:
        if k in doc_text:
            return True
        for syn in _SEMANTIC.get(k, '').split():
            if syn and syn in doc_text:
                return True
    return False


